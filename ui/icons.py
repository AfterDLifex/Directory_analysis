_PIXMAP_CACHE: Dict[str, QPixmap] = {}
_ICON_CACHE: Dict[str, QIcon] = {}


def get_svg_raw(name: str, color: str = "#60a5fa") -> str:
    """Return the raw SVG string with color interpolated."""
    template = SVG_ICONS.get(name.lower(), SVG_ICONS["other"])
    return template.format(color=color)


def get_svg_pixmap(name: str, size: int = 20, color: str = "#60a5fa") -> QPixmap:
    """Render an SVG icon into a high-DPI crisp QPixmap."""
    cache_key = f"{name}:{size}:{color}"
    if cache_key in _PIXMAP_CACHE:
        return _PIXMAP_CACHE[cache_key]

    svg_data = get_svg_raw(name, color)
    renderer = QSvgRenderer(QByteArray(svg_data.encode("utf-8")))

    pixmap = QPixmap(size, size)
    pixmap.fill(Qt.transparent)

    painter = QPainter(pixmap)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing)
    painter.setRenderHint(QPainter.RenderHint.SmoothPixmapTransform)
    renderer.render(painter)
    painter.end()

    _PIXMAP_CACHE[cache_key] = pixmap
    return pixmap


def get_svg_icon(name: str, color: str = "#94a3b8", active_color: str = "#60a5fa", size: int = 20) -> QIcon:
    """Create a multi-state QIcon from SVG for buttons, lists and navigation."""
    cache_key = f"icon:{name}:{color}:{active_color}:{size}"
    if cache_key in _ICON_CACHE:
        return _ICON_CACHE[cache_key]

    normal_pix = get_svg_pixmap(name, size, color)
    active_pix = get_svg_pixmap(name, size, active_color)

    icon = QIcon()
    icon.addPixmap(normal_pix, QIcon.Mode.Normal, QIcon.State.Off)
    icon.addPixmap(active_pix, QIcon.Mode.Normal, QIcon.State.On)
    icon.addPixmap(active_pix, QIcon.Mode.Active)
    icon.addPixmap(active_pix, QIcon.Mode.Selected)

    _ICON_CACHE[cache_key] = icon
    return icon


def get_category_svg_icon(category: str, color: Optional[str] = None, size: int = 18) -> QIcon:
    """Return an icon for a file category."""
    cat_map = {
        "Images": ("image", "#ff6b6b"),
        "Videos": ("video", "#4ecdc4"),
        "Documents": ("document", "#38bdf8"),
        "Audio": ("audio", "#34d399"),
        "Archives": ("archive", "#fbbf24"),
        "Code": ("code", "#f472b6"),
        "Executables": ("executable", "#cbd5e1"),
        "Fonts": ("font", "#818cf8"),
        "System": ("system", "#c084fc"),
        "Other": ("other", "#94a3b8"),
    }
    icon_name, default_color = cat_map.get(category, ("other", "#94a3b8"))
    c = color or default_color
    return get_svg_icon(icon_name, color=c, active_color="#ffffff", size=size)
